CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL UNIQUE,
 hash VARCHAR(255) NOT NULL,
 must_change TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 admin_id INT UNSIGNED NOT NULL,
 expires BIGINT NOT NULL,
 INDEX sessions_expiry(expires),
 FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attempts (
 `key` VARCHAR(180) CHARACTER SET ascii PRIMARY KEY,
 count INT UNSIGNED NOT NULL,
 expires BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (
 id TINYINT NOT NULL PRIMARY KEY,
 data MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS posts (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 slug VARCHAR(160) CHARACTER SET ascii NOT NULL UNIQUE,
 category VARCHAR(100) NOT NULL,
 content MEDIUMTEXT NOT NULL,
 image VARCHAR(200) NOT NULL DEFAULT '',
 status ENUM('draft','published','hidden') NOT NULL,
 created_at VARCHAR(24) NOT NULL,
 updated_at VARCHAR(24) NOT NULL,
 INDEX posts_status_date(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS jobs (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 slug VARCHAR(160) CHARACTER SET ascii NOT NULL UNIQUE,
 location VARCHAR(300) NOT NULL,
 salary VARCHAR(200) NOT NULL,
 schedule VARCHAR(300) NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 description MEDIUMTEXT NOT NULL,
 requirements MEDIUMTEXT NOT NULL,
 benefits MEDIUMTEXT NOT NULL,
 status ENUM('open','closed') NOT NULL,
 created_at VARCHAR(24) NOT NULL,
 updated_at VARCHAR(24) NOT NULL,
 INDEX jobs_status(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS contacts (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 data MEDIUMTEXT NOT NULL,
 status VARCHAR(50) NOT NULL DEFAULT 'Mới',
 notes TEXT NOT NULL,
 created_at VARCHAR(24) NOT NULL,
 INDEX contacts_date(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS files (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 disk_name VARCHAR(80) CHARACTER SET ascii NOT NULL UNIQUE,
 original_name VARCHAR(150) NOT NULL,
 mime VARCHAR(100) CHARACTER SET ascii NOT NULL,
 size INT UNSIGNED NOT NULL,
 public TINYINT NOT NULL DEFAULT 0,
 created_at VARCHAR(24) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS applications (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 job_id CHAR(36) CHARACTER SET ascii NULL,
 data MEDIUMTEXT NOT NULL,
 file_id CHAR(36) CHARACTER SET ascii NULL,
 status VARCHAR(50) NOT NULL DEFAULT 'Mới nhận',
 notes TEXT NOT NULL,
 created_at VARCHAR(24) NOT NULL,
 FOREIGN KEY (job_id) REFERENCES jobs(id),
 FOREIGN KEY (file_id) REFERENCES files(id),
 INDEX applications_job(job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
